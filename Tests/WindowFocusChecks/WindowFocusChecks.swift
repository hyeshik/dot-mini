// Run under NSApplication's actual event loop. Swift Testing's command-line
// runner does not deliver native window occlusion notifications.
@main
struct WindowFocusChecks {
    @MainActor static func main() {
        if CommandLine.arguments.count == 3, CommandLine.arguments[1] == "--hold-shortcut" {
            let app = NSApplication.shared
            app.setActivationPolicy(.accessory)
            let delegate = ShortcutHolder(readyPath: CommandLine.arguments[2])
            app.delegate = delegate
            app.run()
            withExtendedLifetime(delegate) {}
            return
        }
        let app = NSApplication.shared
        app.setActivationPolicy(.accessory)
        let delegate = CheckDelegate()
        app.delegate = delegate
        app.run()
        withExtendedLifetime(delegate) {}
    }

}

@MainActor
private final class ShortcutHolder: NSObject, NSApplicationDelegate {
    let readyPath: String
    private var reference: EventHotKeyRef?
    init(readyPath: String) { self.readyPath = readyPath }
    func applicationDidFinishLaunching(_ notification: Notification) {
        // A separate process models an existing exclusive registration by
        // another app. No physical keyboard events are generated by this check.
        let status = RegisterEventHotKey(80, UInt32(controlKey | optionKey | shiftKey | cmdKey),
            EventHotKeyID(signature: 0x54455354, id: 1), GetApplicationEventTarget(), UInt32(kEventHotKeyExclusive), &reference)
        let message = status == noErr ? "READY" : "ERROR \(status)"
        do { try message.write(toFile: readyPath, atomically: true, encoding: .utf8) }
        catch { exit(1) }
        guard status == noErr, reference != nil else { exit(1) }
        Task.detached {
            _ = readLine()
            await MainActor.run { NSApp.terminate(nil) }
        }
    }
    func applicationWillTerminate(_ notification: Notification) {
        if let reference { UnregisterEventHotKey(reference) }
    }
}

@MainActor
private final class CheckDelegate: NSObject, NSApplicationDelegate {
    func applicationDidFinishLaunching(_ notification: Notification) {
        Task {
            do {
                if CommandLine.arguments.contains("--escape-only") {
                    try await checkEscape()
                    print("PASS: handled web Escape, native dialog Escape, and unhandled Escape dismissal")
                    exit(0)
                }
                if !CommandLine.arguments.contains("--hotkey-only") {
                    try await checkWindow()
                    print("PASS: initial load, 50 hide/show cycles, selected-message refocus, retained draft/view, passive focus, repeated-show no-op, app unhide, minimize/restore, hidden preload, pinning/focus-loss policy")
                    try await checkEscape()
                    print("PASS: handled web Escape, native dialog Escape, and unhandled Escape dismissal")
                }
                try await checkHotKeyConflicts()
                print("PASS: cross-process shortcut conflict, prior binding retained, disabled-event suppression, registration cleanup")
                exit(0)
            } catch {
                print("FAIL: \(error)")
                exit(1)
            }
        }
    }

    private func checkHotKeyConflicts() async throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("YourDotMini-hotkey-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        let ready = directory.appendingPathComponent("ready")
        let child = Process()
        let input = Pipe()
        child.executableURL = URL(fileURLWithPath: CommandLine.arguments[0])
        child.arguments = ["--hold-shortcut", ready.path]
        child.standardInput = input
        child.standardOutput = FileHandle.nullDevice
        child.standardError = FileHandle.nullDevice
        try child.run()
        defer {
            try? input.fileHandleForWriting.close()
            if child.isRunning { child.terminate() }
        }
        try await waitUntil { FileManager.default.fileExists(atPath: ready.path) || !child.isRunning }
        try require((try? String(contentsOf: ready, encoding: .utf8)) == "READY", "test process could not reserve shortcut")

        let service = GlobalHotKeyService()
        defer { service.stop() }
        try checkSystemShortcut(service)
        var presses = 0
        service.onPressed = { presses += 1 }
        let modifiers = GlobalShortcut.control | GlobalShortcut.option | GlobalShortcut.shift | GlobalShortcut.command
        let original = GlobalShortcut(keyCode: 111, modifiers: modifiers) // F12, all modifiers
        let occupied = GlobalShortcut(keyCode: 80, modifiers: modifiers) // F19, all modifiers
        try require(service.apply(original), "test's original shortcut unavailable")
        try require(!service.apply(occupied), "must reject another process's exclusive shortcut")
        try require(service.message.contains("previous shortcut is unchanged"), "conflict must explain recovery")

        // The original registration remains owned after a failed replacement.
        var probe: EventHotKeyRef?
        let conflict = RegisterEventHotKey(111, UInt32(controlKey | optionKey | shiftKey | cmdKey),
            EventHotKeyID(signature: 0x54455354, id: 2), GetApplicationEventTarget(), UInt32(kEventHotKeyExclusive), &probe)
        if let probe { UnregisterEventHotKey(probe) }
        try require(conflict == eventHotKeyExistsErr, "previous shortcut must remain registered")
        try deliverHotKey(id: 1)
        try require(presses == 1, "original event must still invoke toggle")
        try require(service.apply(nil), "disable shortcut")
        try deliverHotKey(id: 1)
        try require(presses == 1, "queued events must not invoke disabled shortcut")

        try input.fileHandleForWriting.close()
        try await waitUntil { !child.isRunning }
        try require(service.apply(occupied), "released shortcut must become available")
        service.stop()
        probe = nil
        let released = RegisterEventHotKey(80, UInt32(controlKey | optionKey | shiftKey | cmdKey),
            EventHotKeyID(signature: 0x54455354, id: 3), GetApplicationEventTarget(), UInt32(kEventHotKeyExclusive), &probe)
        if let probe { UnregisterEventHotKey(probe) }
        try require(released == noErr, "stop must release registration")
    }

    private func deliverHotKey(id: UInt32) throws {
        var event: EventRef?
        let created = CreateEvent(nil, OSType(kEventClassKeyboard), UInt32(kEventHotKeyPressed),
                                  GetCurrentEventTime(), EventAttributes(kEventAttributeUserEvent), &event)
        guard created == noErr, let event else { throw CheckFailure("could not create test event") }
        defer { ReleaseEvent(event) }
        var identifier = EventHotKeyID(signature: 0x59444D4E, id: id)
        let status = SetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID),
                                      MemoryLayout<EventHotKeyID>.size, &identifier)
        try require(status == noErr, "test event identifier")
        _ = SendEventToEventTarget(event, GetApplicationEventTarget())
    }

    private func checkSystemShortcut(_ service: GlobalHotKeyService) throws {
        var keys: Unmanaged<CFArray>?
        guard CopySymbolicHotKeys(&keys) == noErr, let keys else { throw CheckFailure("system shortcut lookup failed") }
        for value in keys.takeRetainedValue() as NSArray {
            guard let entry = value as? NSDictionary,
                  (entry[kHISymbolicHotKeyEnabled] as? NSNumber)?.boolValue == true,
                  let key = (entry[kHISymbolicHotKeyCode] as? NSNumber)?.uint32Value,
                  let raw = (entry[kHISymbolicHotKeyModifiers] as? NSNumber)?.uint32Value,
                  raw & ~UInt32(controlKey | optionKey | shiftKey | cmdKey) == 0 else { continue }
            var modifiers: UInt32 = 0
            if raw & UInt32(controlKey) != 0 { modifiers |= GlobalShortcut.control }
            if raw & UInt32(optionKey) != 0 { modifiers |= GlobalShortcut.option }
            if raw & UInt32(shiftKey) != 0 { modifiers |= GlobalShortcut.shift }
            if raw & UInt32(cmdKey) != 0 { modifiers |= GlobalShortcut.command }
            let shortcut = GlobalShortcut(keyCode: key, modifiers: modifiers)
            guard shortcut.isValid else { continue }
            try require(!service.apply(shortcut) && service.message.contains("macOS uses"), "reserved system shortcut must be rejected")
            print("PASS: enabled system shortcut rejected without changing system settings")
            return
        }
        print("UNVERIFIED: no enabled system shortcut uses the app's supported key choices")
    }

    private func checkWindow() async throws {
        let suite = "YourDotMini.focus-checks.\(UUID().uuidString)"
        guard let defaults = UserDefaults(suiteName: suite) else { throw CheckFailure("test defaults") }
        defer { defaults.removePersistentDomain(forName: suite) }
        let settings = SettingsStore(repository: PreferencesRepository(defaults: defaults))
        settings.update { $0.keepOpen = true }
        let configuration = WKWebViewConfiguration()
        configuration.websiteDataStore = .nonPersistent()
        let webView = FixtureWebView(frame: .zero, configuration: configuration)
        let browser = DotBrowserController(diagnostics: DotDiagnostics(), webView: webView)
        let controller = DotWindowController(browser: browser, settings: settings)
        controller.window?.ignoresMouseEvents = true
        defer { controller.hideDot(); controller.window?.close() }
        try require(!NSApp.isActive, "test must start in the background")
        controller.showDot(activating: false)
        try await waitForFocus(webView, browser: browser, stage: "initial load")
        guard let window = controller.window else { throw CheckFailure("missing window") }
        for cycle in 1...50 {
            _ = try await evaluate(webView, """
                (() => {
                document.getElementById('prompt-textarea').blur();
                const range = document.createRange();
                range.selectNodeContents(document.getElementById('message'));
                getSelection().removeAllRanges(); getSelection().addRange(range);
                return '';
                })()
                """)
            controller.hideDot()
            try require(!browser.composerFocus.isPresented, "hide cancels focus")
            controller.showDot(activating: false)
            try await waitForFocus(webView, browser: browser, stage: "cycle \(cycle)")
            try require(controller.window === window && browser.webView === webView, "same window and web view")
            try require(NSWorkspace.shared.frontmostApplication?.processIdentifier != ProcessInfo.processInfo.processIdentifier && !NSApp.isActive && !window.isKeyWindow,
                        "passive presentation must not activate or make key")
        }
        try require(webView.loadCount == 1, "no reload across 50 cycles")
        let draft = try await evaluate(webView, "document.getElementById('prompt-textarea').value")
        try require(draft == "Fixture unsent draft", "preserve unsent draft")
        _ = try await evaluate(webView, "document.getElementById('other').focus(); ''")
        controller.showDot(activating: false)
        try await Task.sleep(for: .milliseconds(150))
        let active = try await evaluate(webView, "document.activeElement.id")
        try require(active == "other", "already-visible show must not refocus")

        NSApp.hide(nil)
        try await waitUntil { NSApp.isHidden && !browser.composerFocus.isPresented }
        NSApp.unhideWithoutActivation()
        try await waitForFocus(webView, browser: browser, stage: "app unhide")
        try require(NSWorkspace.shared.frontmostApplication?.processIdentifier != ProcessInfo.processInfo.processIdentifier && !NSApp.isActive,
                    "unhide must preserve the other app's focus")

        _ = try await evaluate(webView, "document.getElementById('other').focus(); ''")
        window.miniaturize(nil)
        try await waitUntil { window.isMiniaturized && !browser.composerFocus.isPresented }
        window.deminiaturize(nil)
        try await waitForFocus(webView, browser: browser, stage: "restore from minimized")
        try require(NSWorkspace.shared.frontmostApplication?.processIdentifier != ProcessInfo.processInfo.processIdentifier && !NSApp.isActive,
                    "restore must preserve the other app's focus")

        controller.hideDot()
        browser.returnToDot()
        try await waitUntil { !webView.isLoading }
        try await Task.sleep(for: .milliseconds(150))
        try require(!browser.composerFocus.isPending && !browser.composerFocus.isPresented, "hidden preload must not request focus")
        let hiddenActive = try await evaluate(webView, "document.activeElement.id")
        try require(hiddenActive != "prompt-textarea", "hidden preload must not focus composer")
        controller.showDot(activating: false)
        try await waitForFocus(webView, browser: browser, stage: "show preloaded page")
        try await checkFocusLoss(controller: controller, settings: settings)
    }

    private func checkFocusLoss(controller: DotWindowController, settings: SettingsStore) async throws {
        guard let window = controller.window else { throw CheckFailure("missing focus-loss window") }
        let notification = Notification(name: NSWindow.didResignKeyNotification, object: window)
        controller.windowDidResignKey(notification)
        try await Task.sleep(for: .milliseconds(100))
        try require(window.isVisible, "pinning must prevent automatic dismissal")

        settings.update { $0.keepOpen = false; $0.hideOnFocusLoss = false }
        controller.windowDidResignKey(notification)
        try await Task.sleep(for: .milliseconds(100))
        try require(window.isVisible, "disabled focus-loss dismissal must keep window visible")
        settings.update { $0.hideOnFocusLoss = true }
        controller.isStatusBarInteraction = { true }
        controller.windowDidResignKey(notification)
        try await Task.sleep(for: .milliseconds(100))
        try require(window.isVisible, "status-item interaction must defer to its toggle")
        controller.isStatusBarInteraction = { false }

        controller.windowDidResignKey(notification)
        controller.showDot(activating: false)
        try await Task.sleep(for: .milliseconds(100))
        try require(window.isVisible, "stale queued dismissal must not hide a fresh presentation")
        controller.windowDidResignKey(notification)
        try await waitUntil { !window.isVisible }

        let settingsWindow = NSWindow(contentRect: CGRect(x: 80, y: 120, width: 220, height: 100),
                                      styleMask: [.titled], backing: .buffered, defer: false)
        settingsWindow.title = "Synthetic settings window"
        settingsWindow.isReleasedWhenClosed = false
        settingsWindow.ignoresMouseEvents = true
        defer { settingsWindow.orderOut(nil); settingsWindow.close() }
        settingsWindow.orderFront(nil)
        controller.showDot(activating: false)
        controller.windowDidResignKey(notification)
        try await Task.sleep(for: .milliseconds(100))
        try require(!window.isVisible, "a visible but inactive settings window must not suppress click-away dismissal")

        controller.showDot(activating: false)
        NotificationCenter.default.post(name: NSApplication.didResignActiveNotification, object: NSApp)
        try await waitUntil { !window.isVisible }
        try require(NSWorkspace.shared.frontmostApplication?.processIdentifier != ProcessInfo.processInfo.processIdentifier && !NSApp.isActive,
                    "focus-loss checks must preserve the foreground app")
    }

    private func checkEscape() async throws {
        let suite = "YourDotMini.escape-checks.\(UUID().uuidString)"
        guard let defaults = UserDefaults(suiteName: suite) else { throw CheckFailure("test defaults") }
        defer { defaults.removePersistentDomain(forName: suite) }
        let settings = SettingsStore(repository: PreferencesRepository(defaults: defaults))
        settings.update { $0.keepOpen = true }
        let configuration = WKWebViewConfiguration()
        configuration.websiteDataStore = .nonPersistent()
        let webView = FixtureWebView(frame: .zero, configuration: configuration)
        let browser = DotBrowserController(diagnostics: DotDiagnostics(), webView: webView)
        let controller = DotWindowController(browser: browser, settings: settings)
        guard let window = controller.window else { throw CheckFailure("missing escape window") }
        window.ignoresMouseEvents = true
        defer { controller.hideDot(); window.close() }
        controller.showDot(activating: false)
        try await waitForFocus(webView, browser: browser, stage: "Escape fixture")
        window.makeKey()
        window.makeFirstResponder(webView)
        _ = try await evaluate(webView, """
            window.fixtureEscapeCount = 0;
            window.fixtureEscapeHandler = event => {
                if (event.key === 'Escape') {
                    event.preventDefault();
                    window.fixtureEscapeCount += 1;
                }
            };
            document.addEventListener('keydown', window.fixtureEscapeHandler);
            ''
            """)
        try sendEscape(to: window)
        var handled = false
        for _ in 0..<100 {
            handled = (try await evaluate(webView, "String(window.fixtureEscapeCount)")) == "1"
            if handled { break }
            try await Task.sleep(for: .milliseconds(25))
        }
        try require(handled, "fixture did not receive its native Escape key")
        try require(window.isVisible, "web-owned Escape must not hide the window")
        _ = try await evaluate(webView, "document.removeEventListener('keydown', window.fixtureEscapeHandler); ''")

        let sheet = NSPanel(contentRect: CGRect(x: 0, y: 0, width: 200, height: 100),
                            styleMask: [.titled], backing: .buffered, defer: false)
        sheet.isReleasedWhenClosed = false
        window.beginSheet(sheet, completionHandler: nil)
        window.cancelOperation(nil)
        try require(window.isVisible && window.attachedSheet === sheet, "native sheet must prevent wrapper Escape dismissal")
        window.endSheet(sheet)
        sheet.orderOut(nil)
        sheet.close()
        try await waitUntil { window.attachedSheet == nil }
        window.makeFirstResponder(webView)
        try sendEscape(to: window)
        try await waitUntil { !window.isVisible }
    }

    private func sendEscape(to window: NSWindow) throws {
        for type in [NSEvent.EventType.keyDown, .keyUp] {
            guard let event = NSEvent.keyEvent(with: type, location: .zero, modifierFlags: [],
                timestamp: ProcessInfo.processInfo.systemUptime, windowNumber: window.windowNumber,
                context: nil, characters: "\u{1b}", charactersIgnoringModifiers: "\u{1b}", isARepeat: false, keyCode: 53) else {
                throw CheckFailure("could not create fixture Escape event")
            }
            window.sendEvent(event)
        }
    }

    private func waitForFocus(_ webView: WKWebView, browser: DotBrowserController, stage: String) async throws {
        for _ in 0..<200 {
            if (try? await evaluate(webView, "document.activeElement.id")) == "prompt-textarea",
               !browser.composerFocus.isPending { return }
            try await Task.sleep(for: .milliseconds(25))
        }
        throw CheckFailure("focus timeout at \(stage); presented=\(browser.composerFocus.isPresented), pending=\(browser.composerFocus.isPending)")
    }

    private func evaluate(_ webView: WKWebView, _ script: String) async throws -> String {
        try await withCheckedThrowingContinuation { continuation in
            webView.evaluateJavaScript(script) { result, error in
                if let error { continuation.resume(throwing: error) }
                else { continuation.resume(returning: result as? String ?? "") }
            }
        }
    }

    private func waitUntil(_ predicate: () -> Bool) async throws {
        for _ in 0..<200 {
            if predicate() { return }
            try await Task.sleep(for: .milliseconds(25))
        }
        throw CheckFailure("native visibility transition timed out")
    }

    private func require(_ value: Bool, _ message: String) throws {
        if !value { throw CheckFailure(message) }
    }
    private struct CheckFailure: Error, CustomStringConvertible {
        let description: String
        init(_ description: String) { self.description = description }
    }
}

/// Replaces all URL loads with a static, nonpersistent, network-disabled fixture.
@MainActor
private final class FixtureWebView: WKWebView {
    private(set) var loadCount = 0
    override func load(_ request: URLRequest) -> WKNavigation? {
        loadCount += 1
        return loadHTMLString("""
            <!doctype html><html><head><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'none'"></head>
            <body><input id="other"><p id="message">Synthetic message to select</p>
            <textarea id="prompt-textarea">Fixture unsent draft</textarea></body></html>
            """, baseURL: URL(string: "https://chatgpt.com/dots")!)
    }
}
